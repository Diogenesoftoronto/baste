/** Run from any directory: node site/scripts/build-demo-data.mjs (after npm run build). */
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  basePersonas, generateDesignTokens, exportCSS, exportTailwindConfig,
  exportPandaTheme, generatePrompts, personaToOpenPencil,
} from '../../dist/src/index.js';

const ids = ['cyberbotanist', 'nightmarketcoder', 'liminalweeb'];
const personas = ids.map((id) => ({ ...basePersonas[id], _source: 'base' }));
const tokens = {};
const exports = {};
const prompts = {};
const openpencil = {};

// generatePrompts randomly chooses influences. Freeze that choice for reproducible demos.
let seed = 3456;
const originalRandom = Math.random;
Math.random = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 0x100000000;
};
try {
  for (const persona of personas) {
    const { id } = persona;
    tokens[id] = generateDesignTokens(persona);
    exports[id] = {
      css: exportCSS(persona),
      tailwind: exportTailwindConfig(persona),
      json: JSON.stringify(tokens[id], null, 2),
      panda: exportPandaTheme(persona),
    };
    const preview = generatePrompts(persona, { kind: 'image', purpose: 'hero', description: 'Hero banner' });
    prompts[id] = { personaId: id, image: preview.image, svg: preview.svg, video: preview.video };
    openpencil[id] = personaToOpenPencil(persona, tokens[id]);
    openpencil[id].metadata.exportedAt = 0;
  }
} finally {
  Math.random = originalRandom;
}

const declarations = [
  ['DEMO_PERSONAS', 'PersonaRecord[]', personas],
  ['DEMO_TOKENS', 'Record<string, DesignTokens>', tokens],
  ['DEMO_TOKEN_EXPORTS', 'Record<string, Record<TokenFormat, string>>', exports],
  ['DEMO_PROMPTS', 'Record<string, PromptPreview>', prompts],
  ['DEMO_OPENPENCIL', 'Record<string, OpenPencilDoc>', openpencil],
];
const output = new URL('../src/lib/demo-data.ts', import.meta.url);
mkdirSync(new URL('../src/lib/', import.meta.url), { recursive: true });
writeFileSync(output, [
  '// GENERATED by site/scripts/build-demo-data.mjs. Do not edit by hand.',
  "import type { PersonaRecord, DesignTokens, TokenFormat, PromptPreview, OpenPencilDoc } from './api-types';",
  '',
  ...declarations.map(([name, type, value]) => `export const ${name}: ${type} = ${JSON.stringify(value, null, 2)};\n`),
].join('\n'));
console.log(`Generated ${output.pathname} for ${personas.length} base personas.`);
